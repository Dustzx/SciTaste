"""Render a terminal Native figure contract without modifying its source execution."""

import hashlib
import json

from scitaste.model_nodes.session_exchange import retain_json
from scitaste.state.research_state import FigureContract, ResearchState
from scitaste.visual.critic import VisualTasteCritic, blocking_findings
from scitaste.visual.draft import SemanticDraftGenerator
from scitaste.visual.export import export_drawio, export_svg
from scitaste.visual.patcher import ObjectPatcher


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_contract(project, run, repair=None):
    source = run / "workspace/report/figure_contract.json"
    payload = json.loads(source.read_text())
    binding = None
    if repair is not None:
        path = repair.resolve(strict=True)
        path.relative_to(project)
        record = json.loads(path.read_text())
        if (
            record.get("source") not in {"assistant-session", "subagent-session"}
            or not record.get("author_reference")
            or not record.get("reason")
            or record.get("execution_sha256") != digest(run / "RESULT.json")
            or record.get("original_contract_sha256") != digest(source)
        ):
            raise ValueError("Figure repair is not bound to this terminal model output")
        patch = record["replacement_fields"]
        if not isinstance(patch, dict) or set(patch) - set(FigureContract.model_fields):
            raise ValueError("Unknown figure repair fields")
        repaired = {**payload, **patch}
        if repaired.get("target_claim_ids") != payload.get("target_claim_ids"):
            raise ValueError("Figure format repair cannot change scientific claim targets")
        payload = repaired
        binding = {"locator": path.relative_to(project).as_posix(), "sha256": digest(path)}
    return FigureContract.model_validate(payload), binding


def prepare_native_figure(project, execution, output, *, repair=None):
    root, run, output = (
        project.resolve(strict=True),
        execution.resolve(strict=True),
        output.resolve(),
    )
    run.relative_to(root)
    output.relative_to(root)
    if output.is_relative_to(run) or run.is_relative_to(output):
        raise ValueError("Figure delivery must be separate from execution")
    terminal = json.loads((run / "RESULT.json").read_text())
    if not terminal.get("figure_contract_sha256"):
        return None
    contract_path = run / "workspace/report/figure_contract.json"
    state_path = (root / terminal["research_state"]).resolve(strict=True)
    state_path.relative_to(run)
    if (
        digest(contract_path) != terminal["figure_contract_sha256"]
        or digest(state_path) != terminal["research_state_sha256"]
    ):
        raise ValueError("Terminal figure contract or scientific state changed")
    contract, repair_binding = load_contract(root, run, repair)
    state = ResearchState.model_validate_json(state_path.read_bytes())
    known = {claim.claim_id for claim in state.claims}
    if set(contract.target_claim_ids) - known:
        raise ValueError("Figure targets an unknown canonical claim")
    binding = {
        "execution": run.relative_to(root).as_posix(),
        "execution_sha256": digest(run / "RESULT.json"),
        "figure_contract_sha256": digest(contract_path),
        "state_sha256": digest(state_path),
        "scientific_approval": False,
    }
    if repair_binding is not None:
        binding["figure_contract_repair"] = repair_binding
    if (output / "RESULT.json").is_file():
        retain_json(output / "CONTRACT.json", binding)
        return load_figure_delivery(root, output / "RESULT.json", execution=run)
    if output.exists():
        raise ValueError("Incomplete figure preparation retained; do not overwrite it")
    # CairoSVG is optional; it only consumes SVG generated by our exporter, not
    # arbitrary external SVG or URLs supplied in the model's contract.
    import cairosvg

    output.mkdir(parents=True)
    retain_json(output / "CONTRACT.json", binding)
    objects = SemanticDraftGenerator().generate(contract)
    critic = VisualTasteCritic()
    initial = critic.review(contract, objects, known_claim_ids=known)
    patcher = ObjectPatcher()
    patches = patcher.plan(initial, objects)
    revised = patcher.apply(objects, patches)
    final = critic.review(contract, revised, known_claim_ids=known)
    retain_json(
        output / "REVIEW.json",
        {
            "initial": [item.model_dump(mode="json") for item in initial],
            "patches": [item.model_dump(mode="json") for item in patches],
            "final": [item.model_dump(mode="json") for item in final],
            "review_kind": "deterministic-contract-critic-not-human-visual-review",
        },
    )
    if blocking_findings(final):
        raise ValueError("Figure retains blocking contract findings; artifacts preserved")
    svg = export_svg(contract, revised, output / "figure.svg")
    drawio = export_drawio(contract, revised, output / "figure.drawio")
    pdf = output / "figure.pdf"
    cairosvg.svg2pdf(bytestring=svg.read_bytes(), write_to=str(pdf))
    result = {
        "status": "native-explanatory-figure-delivered",
        **binding,
        "contract_sha256": digest(output / "CONTRACT.json"),
        "artifacts": {
            p.relative_to(root).as_posix(): digest(p)
            for p in (svg, drawio, pdf, output / "REVIEW.json")
        },
        "pdf": pdf.relative_to(root).as_posix(),
        "caption": "Conceptual illustration. " + contract.intended_reader_takeaway,
        "target_claim_statuses": {
            c.claim_id: c.status for c in state.claims if c.claim_id in contract.target_claim_ids
        },
    }
    retain_json(output / "RESULT.json", result)
    return result


def load_figure_delivery(project, result_path, *, execution=None):
    root = project.resolve(strict=True)
    path = result_path.resolve(strict=True)
    path.relative_to(root)
    result = json.loads(path.read_text())
    if result["status"] != "native-explanatory-figure-delivered":
        raise ValueError("Not a completed Native figure delivery")
    run = (root / result["execution"]).resolve(strict=True)
    run.relative_to(root)
    if execution is not None and run != execution.resolve(strict=True):
        raise ValueError("Figure belongs to another execution")
    if digest(run / "RESULT.json") != result["execution_sha256"]:
        raise ValueError("Figure execution binding changed")
    if digest(path.parent / "CONTRACT.json") != result["contract_sha256"]:
        raise ValueError("Figure preparation contract changed")
    binding = json.loads((path.parent / "CONTRACT.json").read_text())
    if any(result.get(key) != value for key, value in binding.items()):
        raise ValueError("Figure receipt differs from its preparation binding")
    terminal = json.loads((run / "RESULT.json").read_text())
    source_contract = run / "workspace/report/figure_contract.json"
    state_path = (root / terminal["research_state"]).resolve(strict=True)
    state_path.relative_to(run)
    if (
        digest(source_contract) != result["figure_contract_sha256"]
        or digest(state_path) != result["state_sha256"]
    ):
        raise ValueError("Figure source changed")
    repair = result.get("figure_contract_repair")
    repair_path = (root / repair["locator"]).resolve(strict=True) if repair else None
    if repair_path is not None:
        repair_path.relative_to(root)
        if digest(repair_path) != repair["sha256"]:
            raise ValueError("Figure repair record changed")
    contract, _ = load_contract(root, run, repair_path)
    state = ResearchState.model_validate_json(state_path.read_bytes())
    statuses = {
        claim.claim_id: claim.status
        for claim in state.claims
        if claim.claim_id in contract.target_claim_ids
    }
    if (
        result["caption"] != "Conceptual illustration. " + contract.intended_reader_takeaway
        or result["target_claim_statuses"] != statuses
    ):
        raise ValueError("Figure caption or claim status changed")
    for locator, expected in result["artifacts"].items():
        artifact = (root / locator).resolve(strict=True)
        artifact.relative_to(path.parent)
        if digest(artifact) != expected:
            raise ValueError("Figure artifact changed")
    if result["pdf"] not in result["artifacts"]:
        raise ValueError("Figure PDF is not source-bound")
    return result
